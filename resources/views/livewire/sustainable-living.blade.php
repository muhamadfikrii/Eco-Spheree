        function exploreSection() {
            return {
                activeChapter: 0,
                
                init() {
                    this.initScrollAnimations();
                },
                
                initScrollAnimations() {
                    const observer = new IntersectionObserver((entries) => {
                        entries.forEach(entry => {
                            if (entry.isIntersecting) {
                                entry.target.classList.add('animate-fade-in-up');
                            }
                        });
                    }, { threshold: 0.1 });
                    
                    // Observe all journey sections
                    document.querySelectorAll('.grid.grid-cols-1').forEach(section => {
                        observer.observe(section);
                    });
                },
                
                startJourney(type) {
                    // Show loading state
                    const button = event.target;
                    const originalText = button.innerHTML;
                    
                    button.innerHTML = `
                        <svg class="animate-spin -ml-1 mr-3 h-5 w-5 text-white" fill="none" viewBox="0 0 24 24">
                            <circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"></circle>
                            <path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
                        </svg>
                        Preparing Your Journey...
                    `;
                    button.disabled = true;
                    
                    // Simulate navigation or API call
                    setTimeout(() => {
                        console.log(`Starting ${type} journey`);
                        // Here you would typically redirect or load specific content
                        
                        // Reset button
                        setTimeout(() => {
                            button.innerHTML = originalText;
                            button.disabled = false;
                        }, 1000);
                    }, 2000);
                }
            }
        }
    </script>

