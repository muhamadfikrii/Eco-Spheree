    <script>
        function contactForm() {
            return {
                form: { name: '', email: '', subject: '', message: '' },
                submitting: false,
                success: false,
                error: false,
                submitForm() {
                    if (
                        !this.form.name ||
                        !this.form.email ||
                        !this.form.subject ||
                        !this.form.message
                    ) {
                        this.error = true;
                        setTimeout(() => (this.error = false), 4000);
                        return;
                    }
                    this.submitting = true;
                    setTimeout(() => {
                        this.submitting = false;
                        this.success = true;
                        this.form = {
                            name: '',
                            email: '',
                            subject: '',
                            message: '',
                        };
                        setTimeout(() => (this.success = false), 5000);
                    }, 1500);
                },
            };
        }
